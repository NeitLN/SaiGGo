"""Test phần đọc nội dung của scripts/check_attribution.py (không gọi git)."""

import importlib.util
from pathlib import Path

import pytest

_path = Path(__file__).resolve().parent.parent / "scripts" / "check_attribution.py"
_spec = importlib.util.spec_from_file_location("check_attribution", _path)
ca = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(ca)

ALLOWED = {"tien.vo539@gmail.com", "188600692+dobaovlu@users.noreply.github.com"}


def problems(text: str) -> list[str]:
    return ca.check_text(text, ALLOWED, "x")


def test_member_co_author_is_allowed():
    assert problems("Sửa test\n\nCo-authored-by: Bảo <188600692+dobaovlu@users.noreply.github.com>") == []


def test_unknown_co_author_is_rejected():
    assert len(problems("Sửa test\n\nCo-Authored-By: Ai đó <someone@example.com>")) == 1


@pytest.mark.parametrize("line", [
    "🤖 Generated with [Tool](https://example.com)",
    "  🤖 Generated by Tool",
    "- 🤖 Generated by Tool",
    "Generated with [Tool](https://example.com)",
    "- Generated with [Tool](https://example.com)",
    "* Generated  with [Tool](https://example.com)",
])
def test_promo_line_is_rejected(line):
    assert len(problems(f"Mô tả PR\n\n{line}\n")) == 1


@pytest.mark.parametrize("text", [
    "- Generated by create_backlog.py từ TASKS.md",      # file sinh tự động của nhóm (góp ý của Bảo ở #60)
    "Generated by burndown.py",
    "Cụm Generated with [x] ở giữa câu thì không tính",
    "Generated by\n[link](https://example.com)",          # khác dòng
])
def test_normal_text_is_allowed(text):
    assert problems(text) == []
